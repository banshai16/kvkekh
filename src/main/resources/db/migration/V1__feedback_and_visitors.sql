-- Feedback submissions: kept as a backup of the emailed copy, deleted after feedback.retention.
CREATE TABLE feedback (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference   VARCHAR(16)  NOT NULL UNIQUE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    name        VARCHAR(100) NOT NULL,
    location    VARCHAR(100) NOT NULL,
    email       VARCHAR(254) NOT NULL,
    message     VARCHAR(2000) NOT NULL,
    mail_status VARCHAR(20)  NOT NULL,
    mail_error  VARCHAR(500)
);
CREATE INDEX feedback_created_at ON feedback (created_at);

-- Visitor counter. No IP addresses are stored: each visitor is a keyed hash that changes every day,
-- and yesterday's hashes are deleted, so visits cannot be linked across days.
CREATE TABLE visitor_total (
    id    INT    PRIMARY KEY,
    total BIGINT NOT NULL
);

CREATE TABLE visitor_seen (
    visit_day DATE     NOT NULL,
    visitor CHAR(64) NOT NULL,
    PRIMARY KEY (visit_day, visitor)
);

-- Server-side secrets generated on first start (e.g. the visitor-hash key).
CREATE TABLE app_secret (
    name   VARCHAR(50)  PRIMARY KEY,
    secret VARCHAR(128) NOT NULL
);
